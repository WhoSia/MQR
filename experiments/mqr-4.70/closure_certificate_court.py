#!/usr/bin/env python3
import csv, itertools, pathlib
from collections import defaultdict

ROOT=pathlib.Path(__file__).resolve().parent

def read_tsv(path):
    with open(path,newline="") as f:
        return list(csv.DictReader(f,delimiter="\t"))

def load():
    rows=read_tsv(ROOT/"RESPONSE-MATRIX-FREEZE.tsv")
    H=[r["history"] for r in rows]
    T=[k for k in rows[0] if k!="history"]
    R={(r["history"],t):r[t] for r in rows for t in T}
    fam_rows=read_tsv(ROOT/"PROBE-FAMILIES-FREEZE.tsv")
    F={r["family_id"]:([] if r["members"]=="-" else r["members"].split(",")) for r in fam_rows}
    return H,T,R,F

def joint_signature(H,R,U):
    return {h:tuple(R[(h,t)] for t in U) for h in H}

def partition(H,R,U):
    b=defaultdict(list)
    sig=joint_signature(H,R,U)
    for h in H:b[sig[h]].append(h)
    return tuple(sorted(tuple(v) for v in b.values()))

def reconstructible(H,R,U,t):
    # t is a deterministic function of the joint U response iff equal U-signatures never disagree on t.
    sig=joint_signature(H,R,U)
    seen={}
    for h in H:
        s=sig[h]; y=R[(h,t)]
        if s in seen and seen[s]!=y:return False
        seen[s]=y
    return True

def exterior_splitters(H,T,R,U):
    p=partition(H,R,U)
    collapsed=[]
    for c in p:
        collapsed.extend(itertools.combinations(c,2))
    ext=[t for t in T if t not in U]
    split={}
    for t in ext:
        pairs=[(a,b) for a,b in collapsed if R[(a,t)]!=R[(b,t)]]
        if pairs:split[t]=pairs
    return split

def family_cert(H,T,R,U):
    split=exterior_splitters(H,T,R,U)
    rec={t:reconstructible(H,R,U,t) for t in T}
    # C1: finite envelope was exhaustively checked and no frozen exterior test refines.
    c1=(len(split)==0)
    # C2: every frozen admissible test is a deterministic function of joint U response.
    c2=all(rec.values())
    # C3: no frozen test separates any U-equivalent pair.
    c3=(len(split)==0)
    # C4 deterministic finite analogue: E_U Blackwell-dominates every frozen single-test experiment,
    # because every test outcome can be generated by a deterministic channel from E_U.
    c4=all(rec.values())
    return c1,c2,c3,c4,split,rec

def minimal_cover_families(H,T,R):
    good=[]
    for k in range(len(T)+1):
        for U in itertools.combinations(T,k):
            c1,c2,c3,c4,_,_=family_cert(H,T,R,list(U))
            if c4:good.append(U)
        if good:return good
    return []

def main():
    H,T,R,F=load()
    out=ROOT/"results";out.mkdir(exist_ok=True)

    rows=[]
    for fid,U in sorted(F.items()):
        c1,c2,c3,c4,split,rec=family_cert(H,T,R,U)
        rows.append([
            fid,",".join(U) or "-",len(partition(H,R,U)),
            str(c1).upper(),str(c2).upper(),str(c3).upper(),str(c4).upper(),
            ",".join(sorted(split)) or "-"
        ])

    mins=minimal_cover_families(H,T,R)

    with open(out/"closure_certificates.tsv","w",newline="") as f:
        w=csv.writer(f,delimiter="\t",lineterminator="\n")
        w.writerow(["family_id","members","class_count","C1_finite_envelope","C2_response_closure","C3_partition_closure","C4_deterministic_Blackwell","exterior_splitters"])
        w.writerows(rows)

    with open(out/"closure_minimal_families.tsv","w",newline="") as f:
        w=csv.writer(f,delimiter="\t",lineterminator="\n")
        w.writerow(["rank","size","members"])
        for i,U in enumerate(mins,1):w.writerow([i,len(U),",".join(U)])

    byid={r[0]:r for r in rows}
    ok=(
        byid["F_AB"][3]=="FALSE"
        and byid["F_AB"][4]=="FALSE"
        and byid["F_AB"][5]=="FALSE"
        and byid["F_AB"][6]=="FALSE"
        and set(byid["F_AB"][7].split(","))=={"C","K","P"}
        and byid["F_ABC"][3:7]==["TRUE","TRUE","TRUE","TRUE"]
        and len(mins)==24
        and len(mins[0])==3
    )

    # In this finite deterministic world C1/C3 and C2/C4 coincide across all named families.
    c13=all(r[3]==r[5] for r in rows)
    c24=all(r[4]==r[6] for r in rows)

    print("MQR470_CLOSURE_COURT="+("PASS" if ok else "FAIL"))
    print("MQR470_F_AB_EXTERIOR_SPLITTERS="+byid["F_AB"][7])
    print("MQR470_F_ABC_C4="+byid["F_ABC"][6])
    print("MQR470_MINIMAL_C4_FAMILY_COUNT="+str(len(mins)))
    print("MQR470_MINIMAL_C4_FAMILY_SIZE="+str(len(mins[0]) if mins else -1))
    print("MQR470_C1_C3_COLLAPSE="+("YES" if c13 else "NO"))
    print("MQR470_C2_C4_COLLAPSE="+("YES" if c24 else "NO"))
    return 0 if ok else 1

if __name__=="__main__":
    raise SystemExit(main())
